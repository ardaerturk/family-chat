export function translate(
  language: Language,
  key: string,
  values?: Record<string, string | number>,
) {
  const text = language === "tr" ? (turkish[key] ?? key) : key;
  return values
    ? text.replace(/\{(\w+)\}/g, (match, name: string) =>
        String(values[name] ?? match),
      )
    : text;
}
